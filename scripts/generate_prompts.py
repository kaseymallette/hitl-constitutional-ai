"""Generate prompts for an experiment with a local model in Ollama.

Each section in `data/seeds.json` is divided into categories, and each category
has its own description and seed prompts. Prompts are generated by stratified
sampling: every category gets the same number of prompts, and when writing a
prompt for a category the model sees only that category's description and
examples. As in self-instruct, the examples mix two seeds with two prompts the
model already wrote for the same category, so the prompts drift less toward the
seeds.

Every generated prompt is written by the same speaker, described in
`data/speaker.txt`. Prompts that mention a spouse, children, or siblings are
rejected, because the speaker has none and the model otherwise defaults to
them. No more than three prompts in a section may start with the same four
words.

The output is appended to the file given by `--out`, so the script can be
stopped and restarted without losing work.

Usage:
    .venv\\Scripts\\python.exe scripts\\generate_prompts.py --section 1.1 --out experiments\\1.1\\prompts.jsonl
"""

import argparse
import json
import random
import re
import urllib.request
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEEDS = ROOT / "data" / "seeds.json"
SPEAKER = ROOT / "data" / "speaker.txt"
OLLAMA_URL = "http://localhost:11434/api/chat"

SPEAKER_BIO = SPEAKER.read_text(encoding="utf-8").strip()

SYSTEM = (
    "You write messages that one particular person might send to an AI assistant. "
    f"{SPEAKER_BIO} "
    "Her messages show how she notices and wonders about the world, as well as her everyday life. "
    "Her job comes up only sometimes. "
    "Write exactly one new message, in her own voice, as she would type it. "
    "Do not mention a husband, wife, spouse, marriage, wedding, pregnancy, babies, children, or siblings. "
    "Do not answer the message, explain it, or add anything else."
)

# Rejects prompts that contradict the speaker's bio.
EXCLUDED = re.compile(
    r"\b(husband|wife|spouse|married|marriage|wedding|fianc\w*|pregnan\w*|baby|babies|newborn|"
    r"kid|kids|child|children|son|sons|daughter|daughters|toddler|parenting|"
    r"sister|sisters|brother|brothers|sibling|siblings)\b",
    re.IGNORECASE,
)

SCHEMA = {
    "type": "object",
    "properties": {"message": {"type": "string"}},
    "required": ["message"],
}


def normalize(text: str) -> str:
    return re.sub(r"[^a-z0-9 ]", "", text.lower()).strip()


def opening(text: str) -> str:
    """The first four words, used to stop one opening from spreading through a section."""
    return " ".join(normalize(text).split()[:4])


def chat(model: str, user: str, temperature: float) -> str | None:
    body = json.dumps({
        "model": model,
        "messages": [{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}],
        "format": SCHEMA,
        "stream": False,
        "options": {"temperature": temperature},
    }).encode()
    request = urllib.request.Request(OLLAMA_URL, data=body, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=120) as response:
        content = json.loads(response.read())["message"]["content"]
    try:
        message = json.loads(content)["message"]
    except (json.JSONDecodeError, KeyError, TypeError):
        return None
    message = message.strip().strip('"').strip()
    return message or None


def ask(model: str, category: dict, examples: list[str], temperature: float) -> str | None:
    shown = "\n".join(f"- {e}" for e in examples)
    user = (
        f"The message must be of this kind: {category['description']}\n\n"
        f"Examples:\n{shown}\n\n"
        "Write one new message of exactly this kind, about a different topic from the examples. "
        "Being this kind of message matters most; her voice and interests come second. "
        "Keep it about as long as the examples. "
        'Respond as JSON: {"message": "..."}'
    )
    return chat(model, user, temperature)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--section", required=True, help="section to generate, e.g. 1.1")
    parser.add_argument("--out", type=Path, required=True, help="JSONL file to append prompts to")
    parser.add_argument("--categories", nargs="*", help="only these categories")
    parser.add_argument("--per-category", type=int, default=50)
    parser.add_argument("--model", default="llama3.2:3b")
    parser.add_argument("--temperature", type=float, default=1.0)
    parser.add_argument("--max-attempts", type=int, default=5, help="attempts per accepted prompt")
    parser.add_argument("--max-same-opening", type=int, default=3,
                        help="prompts per section that may start with the same four words")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    rng = random.Random(args.seed)
    sections = {s["section"]: s for s in json.loads(SEEDS.read_text(encoding="utf-8"))}
    section = sections[args.section]
    categories = section["categories"]
    if args.categories:
        categories = [c for c in categories if c["category"] in args.categories]

    existing = defaultdict(list)
    if args.out.exists():
        for line in args.out.read_text(encoding="utf-8-sig").splitlines():
            record = json.loads(line)
            existing[record["category"]].append(record["prompt"])

    all_prompts = [p for prompts in existing.values() for p in prompts]
    seen = {normalize(p) for p in all_prompts}
    openings = Counter(opening(p) for p in all_prompts)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("a", encoding="utf-8", newline="\n") as out:
        for category in categories:
            name = category["category"]
            seeds = category["examples"]
            generated = existing[name]
            seen |= {normalize(s) for s in seeds}
            attempts = 0
            while len(generated) < args.per_category and attempts < args.per_category * args.max_attempts:
                attempts += 1
                pool = rng.sample(seeds, min(2, len(seeds)))
                if len(generated) >= 2:
                    pool += rng.sample(generated, 2)
                else:
                    pool = rng.sample(seeds, len(seeds))
                rng.shuffle(pool)

                message = ask(args.model, category, pool, args.temperature)
                if not message or not (10 <= len(message) <= 1500) or normalize(message) in seen:
                    continue
                if EXCLUDED.search(message):
                    continue
                if openings[opening(message)] >= args.max_same_opening:
                    continue
                openings[opening(message)] += 1
                seen.add(normalize(message))
                generated.append(message)
                record = {
                    "id": f"{args.section}-{name}-{len(generated) - 1:03d}",
                    "section": args.section,
                    "category": name,
                    "prompt": message,
                }
                out.write(json.dumps(record, ensure_ascii=False) + "\n")
                out.flush()
            print(f"{args.section} {category['title']}: {len(generated)} prompts ({attempts} attempts this run)")


if __name__ == "__main__":
    main()
